#!/usr/bin/env python3
"""
Generate the hephaistos wordmark as SVG path data from a font file.

The letters are converted to outlines, so the wordmark renders identically
everywhere and scales without the dot drifting. The tittle (dot) of the "i"
is taken from the font's own "i" glyph, so it sits exactly where the type
designer put it, and is emitted separately as a circle so it can be coloured.

Usage:
  pip install fonttools uharfbuzz
  python3 scripts/generate-wordmark.py path/to/Inter-ExtraBold.ttf \
      [--tracking -0.04] [--dot-scale 1.0] > app/components/wordmark-data.ts

--tracking is letter spacing in em (CSS letter-spacing equivalent).
--dot-scale enlarges/shrinks the dot around its own centre.
"""
import argparse
import sys

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

TEXT = "hephaistos"


def split_contours(recording):
    contours, current = [], []
    for op, args in recording.value:
        current.append((op, args))
        if op in ("closePath", "endPath"):
            contours.append(current)
            current = []
    return contours


def replay(contour, pen):
    for op, args in contour:
        getattr(pen, op)(*args)


def fmt(n):
    return f"{n:.1f}".rstrip("0").rstrip(".")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("font")
    ap.add_argument("--tracking", type=float, default=-0.04)
    ap.add_argument("--dot-scale", type=float, default=1.0)
    a = ap.parse_args()

    font = TTFont(a.font)
    glyphset = font.getGlyphSet()
    upem = font["head"].unitsPerEm
    tracking = a.tracking * upem

    blob = hb.Blob.from_file_path(a.font)
    hbfont = hb.Font(hb.Face(blob))
    buf = hb.Buffer()
    buf.add_str(TEXT)
    buf.guess_segment_properties()
    hb.shape(hbfont, buf, {"kern": True, "liga": False})

    order = font.getGlyphOrder()
    i_glyph = font.getBestCmap()[ord("i")]

    letters = SVGPathPen(glyphset, ntos=fmt)
    bounds = BoundsPen(glyphset)
    dot_bounds = None
    x = 0.0
    n = len(buf.glyph_infos)
    for idx, (info, pos) in enumerate(zip(buf.glyph_infos, buf.glyph_positions)):
        name = order[info.codepoint]
        gx, gy = x + pos.x_offset, pos.y_offset
        # Flip y: font units are y-up, SVG is y-down.
        t = (1, 0, 0, -1, gx, -gy)
        rec = DecomposingRecordingPen(glyphset)
        glyphset[name].draw(rec)
        contours = split_contours(rec)
        if name == i_glyph:
            # The tittle is the contour whose lowest point is highest.
            def ymin(c):
                bp = BoundsPen(glyphset)
                replay(c, bp)
                return bp.bounds[1]
            dot = max(contours, key=ymin)
            contours = [c for c in contours if c is not dot]
            bp = BoundsPen(glyphset)
            replay(dot, TransformPen(bp, t))
            dot_bounds = bp.bounds
        for c in contours:
            replay(c, TransformPen(letters, t))
            replay(c, TransformPen(bounds, t))
        x += pos.x_advance + (tracking if idx < n - 1 else 0)

    if dot_bounds is None:
        sys.exit("no 'i' found")

    x0, y0, x1, y1 = dot_bounds
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    r = (x1 - x0 + y1 - y0) / 4 * a.dot_scale

    bx0, by0, bx1, by1 = bounds.bounds
    top = min(by0, cy - r)
    bottom = by1  # descender of the "p", below baseline (y > 0)
    width = bx1 - bx0
    height = bottom - top

    print("// Generated by scripts/generate-wordmark.py — do not edit by hand.")
    print(f"// Source font: Inter ExtraBold, tracking {a.tracking}em, dot scale {a.dot_scale}.")
    print("export const wordmark = {")
    print(f"  unitsPerEm: {upem},")
    print(f"  viewBox: '{fmt(bx0)} {fmt(top)} {fmt(width)} {fmt(height)}',")
    print(f"  width: {fmt(width)},")
    print(f"  height: {fmt(height)},")
    print(f"  /** Distance from the baseline down to the bottom of the viewBox. */")
    print(f"  descent: {fmt(bottom)},")
    print(f"  letters: '{letters.getCommands()}',")
    print(f"  dot: {{ cx: {fmt(cx)}, cy: {fmt(cy)}, r: {fmt(r)} }},")
    print("} as const")


if __name__ == "__main__":
    main()
