import type { ReactNode } from 'react'
import { cssVars } from './css-vars'
import { wordmark } from './wordmark-data'

const em = (units: number) => `${units / wordmark.unitsPerEm}em`

type Props = {
  className?: string
  /** Optical tweak: enlarge the dot at small sizes (e.g. 1.2 in a nav bar). */
  dotScale?: number
  /** Render as a block box (no baseline alignment). Used when overlaying annotations. */
  block?: boolean
  /** Extra SVG drawn in the wordmark's own coordinate system (font units, baseline at y = 0). */
  children?: ReactNode
}

/**
 * The hephaistos wordmark as outlined SVG.
 *
 * Sized in `em`: at a given font-size the letters match Inter ExtraBold set at
 * that size, so scale it with `font-size` like text. Inline, the baseline lines
 * up with surrounding text. Letters use `currentColor`, the dot uses `--accent`.
 * The dot can grow a little past the box; overflow is visible for that.
 * Sizing rules are `.wordmark` in app.css; this passes the geometry as --wm-*.
 *
 * Geometry lives in wordmark-data.ts, generated by scripts/generate-wordmark.py.
 */
export default function Wordmark({ className, dotScale = 1, block = false, children }: Props) {
  return (
    <svg
      className={['wordmark', block && 'wordmark--block', className].filter(Boolean).join(' ')}
      viewBox={wordmark.viewBox}
      role="img"
      aria-label="hephaistos"
      style={cssVars({
        '--wm-width': em(wordmark.width),
        '--wm-height': em(wordmark.height),
        '--wm-descent': em(wordmark.descent),
      })}
    >
      <path d={wordmark.letters} fill="currentColor" />
      <circle cx={wordmark.dot.cx} cy={wordmark.dot.cy} r={wordmark.dot.r * dotScale} fill="var(--accent)" />
      {children}
    </svg>
  )
}
